// Helper tạo mã cont chuẩn ISO 6346
function makeIsoCont(prefix: string, serial6: string): string {
  const first10 = prefix.toUpperCase() + serial6;
  const cd = calculateCheckDigit(first10) ?? 0;
  return first10 + cd;
}

